final Map<String, Interest> _byKey = {
  for (final c in interestCategories)
    for (final i in c.items) i.key: i,
};

/// Interesse zum Schlüssel; unbekannte (z. B. aus neuerer App-Version) → null.
Interest? interestByKey(String key) => _byKey[key];

InterestCategory? categoryByKey(String key) {
  for (final c in interestCategories) {
    if (c.key == key) return c;
  }
  return null;
}

/// Groß-/Kleinschreibung und Umlaute egal: „zelda“ findet „Zelda“,
/// „baeren“ findet „Bären“.
String normalizeForSearch(String s) => s
    .toLowerCase()
    .replaceAll('ä', 'ae')
    .replaceAll('ö', 'oe')
    .replaceAll('ü', 'ue')
    .replaceAll('ß', 'ss')
    .replaceAll(RegExp(r'[^a-z0-9]+'), ' ')
    .trim();

/// Sucht in allen Kategorien (oder nur in [category]).
List<Interest> searchInterests(String query, {String? category}) {
  final q = normalizeForSearch(query);
  final result = <Interest>[];
  for (final c in interestCategories) {
    if (category != null && c.key != category) continue;
    for (final i in c.items) {
      if (q.isEmpty || normalizeForSearch(i.label).contains(q)) result.add(i);
    }
  }
  return result;
}

/// Prüft eine Auswahl: höchstens [maxPerCategory] pro Kategorie, nur bekannte.
String? validateInterests(Iterable<String> keys) {
  final counts = <String, int>{};
  for (final k in keys) {
    final i = interestByKey(k);
    if (i == null) return 'Unbekanntes Interesse.';
    counts[i.category] = (counts[i.category] ?? 0) + 1;
  }
  for (final e in counts.entries) {
    if (e.value > maxPerCategory) {
      return 'Höchstens $maxPerCategory pro Kategorie '
          '(${categoryByKey(e.key)!.label}).';
    }
  }
  return null;
}
