class Interest {
  const Interest(this.key, this.emoji, this.label);

  /// Vollständiger Schlüssel, z. B. `music.jazz`.
  final String key;
  final String emoji;
  final String label;

  String get category => key.split('.').first;
  String get display => '$emoji $label';
}

